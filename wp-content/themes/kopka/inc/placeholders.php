function kopka39_hide_placeholders( $html ) {
	if ( false === strpos( $html, '[' ) ) {
		return $html;
	}
	$token = '\[[А-ЯЁA-Z][А-ЯЁA-Z_]{2,}\]';
	if ( ! preg_match( '/' . $token . '/u', $html ) ) {
		return $html;
	}

	// 1. Известные фразы.
	$html = strtr( $html, kopka39_placeholder_phrases() );

	// 2. Строки таблиц, где значение — заглушка.
	$html = preg_replace( '#<tr\b[^>]*>(?:(?!</tr>).)*?<td\b[^>]*>\s*' . $token . '\s*</td>(?:(?!</tr>).)*?</tr>\s*#su', '', $html );
	// Пустые таблицы, пустые обёртки, раздел с одним заголовком.
	$html = preg_replace( '#<table\b[^>]*>\s*(?:<tbody>\s*</tbody>\s*)?</table>\s*#su', '', $html );
	$html = preg_replace( '#<div class="fse-group">\s*</div>\s*#su', '', $html );
	$html = preg_replace( '#<section\b[^>]*>\s*<div class="fse-group fse-section-header">\s*<h2\b[^>]*>[^<]*</h2>\s*</div>\s*</section>\s*#su', '', $html );

	// 3. Неизвестные фразы с заглушкой — убираем предложение целиком
	//    (в пределах текста, не задевая теги).
	$html = preg_replace( '#[^.!?<>"]*' . $token . '[^.!?<>"]*[.!?]?\s?#u', '', $html );

	// 4. Опустевшие абзацы и пункты списков.
	$html = preg_replace( '#<(p|li)\b[^>]*>\s*</\1>\s*#u', '', $html );
	return $html;
}

function kopka39_hide_placeholders_start() {
	if ( is_admin() || is_feed() || wp_doing_ajax() || ( defined( 'REST_REQUEST' ) && REST_REQUEST ) || is_customize_preview() ) {
		return;
	}
	ob_start( 'kopka39_hide_placeholders' );
}
add_action( 'template_redirect', 'kopka39_hide_placeholders_start', 1 );

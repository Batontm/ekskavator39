 *  - то же самое — в разметке schema.org (FAQ).
 *
 * Как только в inc/site-data.php или в тексте страницы появится
 * настоящее значение, оно покажется само — фильтр трогает только
 * квадратные скобки с заглавными буквами.
 *
 * Отключить — закомментировать add_action в конце файла.
 *
 * @package kopka
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}


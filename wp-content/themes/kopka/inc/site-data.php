/**
 * Возвращает значение по ключу: kopka_d('phone')
 */
function kopka_d( $key ) {
	$data = kopka_site_data();
	return isset( $data[ $key ] ) ? $data[ $key ] : '';
}

/**
 * То же, но экранированное для вывода в HTML.
 */
function kopka_e( $key ) {
	echo esc_html( kopka_d( $key ) );
}

